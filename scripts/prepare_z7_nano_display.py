"""Derive the new-board display platform after the physical DDR check."""
import json
from run_z7_nano import ROOT, OUT, sha


def main():
    board = json.loads((ROOT/"hardware/z7_nano/source.json").read_text(encoding="utf-8"))
    ddr = json.loads((OUT/"ddr/run.json").read_text(encoding="utf-8"))
    if ddr["status"] != "passed" or any(sha(ROOT/p) != digest for p, digest in ddr["input_hashes"].items()):
        raise RuntimeError("Current new-board DDR verification required")
    folder = OUT/"display"
    folder.mkdir(parents=True, exist_ok=True)
    params = dict(board["PSParameters"])
    params.update(PCW_USE_M_AXI_GP0="1", PCW_USE_S_AXI_HP0="1", PCW_S_AXI_HP0_DATA_WIDTH="64",
                  PCW_EN_CLK0_PORT="0", PCW_EN_RST0_PORT="0")
    pairs = "\n".join(f"    CONFIG.{key} {{{value}}} \\" for key, value in sorted(params.items()))
    (folder/"ps7_config.tcl").write_text(
        "# Derived from hardware/z7_nano/source.json and the display interface.\n"
        "proc configure_nano_display_ps {cell} {\n    set_property -dict [list \\\n"
        + pairs + "\n    ] $cell\n}\n", encoding="utf-8")
    timer_ticks = int(float(params["PCW_APU_PERIPHERAL_FREQMHZ"])*1000/2)
    (folder/"framebuffer_hw.h").write_text(
        "/* Generated by prepare_z7_nano_display.py. */\n"
        "#define FB_WIDTH 1024u\n#define FB_HEIGHT 600u\n#define FB_STRIDE 4096u\n"
        "#define FB_BASE0 0x01000000u\n#define FB_BASE1 0x01400000u\n"
        "#define VDMA_BASE 0x43c00000u\n#define VIDEO_BASE 0x43c10000u\n"
        f"#define TIMER_TICKS_PER_MS {timer_ticks}u\n", encoding="utf-8")
    (folder/"configuration.json").write_text(json.dumps({
        "board_source_sha256": sha(ROOT/"hardware/z7_nano/source.json"), "parameters": params,
        "width": 1024, "height": 600, "stride": 4096, "format": "XRGB8888",
        "buffers": [0x01000000, 0x01400000], "vdma_base": 0x43c00000, "video_base": 0x43c10000,
        "timer_ticks_per_ms": timer_ticks, "usr_access": 0x5a374e32,
        "scope": "Generated display configuration; USB Host is not initialized"
    }, indent=2)+"\n", encoding="utf-8")
    print("PASS_Z7_NANO_DISPLAY_PREPARE")


if __name__ == "__main__":
    main()
